// Writes the platform files from tokens.json, the single source of colour (PRD v4 B5).
// Usage: node build-tokens.mjs (write) | node build-tokens.mjs --check (fail when a file is stale).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(fs.readFileSync(path.join(here, "tokens.json"), "utf8"));
const { cassyLight, cassyDark } = tokens.themes;

// Guest app names (globals.css) for each semantic token. The guest primary is the neutral ink fallback
// (PRD v4 Q9); the outlet colour replaces it at runtime. The focus ring stays ink so any outlet colour keeps it visible.
const webVars = (t) => [
  ["--bg-canvas", t.bgCanvas],
  ["--bg-surface", t.bgSurface],
  ["--bg-muted", t.bgMuted],
  ["--text-primary", t.textPrimary],
  ["--text-secondary", t.textSecondary],
  ["--border-subtle", t.borderSubtle],
  ["--border-strong", t.borderStrong],
  ["--brand-primary", t.guestPrimary],
  ["--brand-on-primary", t.guestOnPrimary],
  ["--brand-accent", t.brandAccent],
  ["--brand-accent-text", t.brandAccentText],
  ["--state-ok-bg", t.okBg],
  ["--state-ok-fg", t.okFg],
  ["--state-warn-bg", t.warnBg],
  ["--state-warn-fg", t.warnFg],
  ["--state-err-bg", t.errBg],
  ["--state-err-fg", t.errFg],
  ["--state-info-bg", t.infoBg],
  ["--state-info-fg", t.infoFg],
  ["--focus-ring", t.textPrimary]
];

const block = (selector, t) => `${selector} {\n${webVars(t).map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;

const outputs = {
  "../../apps/web/src/app/tokens.css":
    "/* Generated by packages/design-tokens/build-tokens.mjs from tokens.json. Do not edit by hand. */\n\n" +
    block(':root,\n[data-theme="light"]', cassyLight) +
    "\n" +
    block('[data-theme="dark"]', cassyDark)
};

const check = process.argv.includes("--check");
let stale = false;
for (const [rel, content] of Object.entries(outputs)) {
  const file = path.join(here, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (current === content) continue;
  if (check) {
    console.error(`[FAIL] ${rel} is out of date; run node packages/design-tokens/build-tokens.mjs`);
    stale = true;
  } else {
    fs.writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
if (stale) process.exit(1);
